"""Generate frozen separated-store row codecs from the source-bound DDL catalogue.

Only --write changes files. Neither mode reads retained catalogues. Generated
modules use only the standard library and do not execute SQL or inspect schemas.
"""

from __future__ import annotations

import argparse
import json
import os
import stat
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if __package__ in (None, ""):
    sys.path.insert(0, str(ROOT))

from scripts.persistence_model import (  # noqa: E402
    TARGET_FORMATS,
    load_model,
    row_type_binding,
    validate_model,
)
from scripts.schema_catalog import build_catalog  # noqa: E402

SQL_TYPES = {"TEXT": "str", "INTEGER": "int", "BLOB": "bytes"}

HEADER = '''"""Generated {domain} row codecs; edit DDL/mapping, then run the generator.

Source store: {store}
DDL SHA-256: {digest}
Generated by scripts/generate_persistence_rows.py --write.
Rows describe full records; partial projections remain separate DTOs.
"""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass
from sqlite3 import Row
from typing import ClassVar, Self

_Value = str | int | bytes | None


class _Row:
    """Strict primitive row binding; SQL defaults are applied by SQLite only."""

    COLUMNS: ClassVar[tuple[str, ...]]
    WRITE_COLUMNS: ClassVar[tuple[str, ...]]
    KEY_COLUMNS: ClassVar[tuple[str, ...]]
    _CODECS: ClassVar[tuple[tuple[type, bool], ...]]
    _DEFAULT_COLUMNS: ClassVar[frozenset[str]] = frozenset()

    @classmethod
    def _validate_value(cls, column: str, value: object) -> None:
        expected, nullable = cls._CODECS[cls.COLUMNS.index(column)]
        if value is None and nullable:
            return
        if type(value) is not expected:
            suffix = " or None" if nullable else ""
            raise TypeError(
                f"{{cls.__name__}}.{{column}} requires {{expected.__name__}}{{suffix}}"
            )

    def __post_init__(self) -> None:
        for column in self.COLUMNS:
            self._validate_value(column, getattr(self, column))

    @staticmethod
    def _values(record: Mapping[str, object] | Row) -> dict[str, object]:
        keys = list(record.keys())
        if len(set(keys)) != len(keys):
            raise ValueError("duplicate record columns")
        return {{column: record[column] for column in keys}}

    @classmethod
    def from_record(cls, record: Mapping[str, object] | Row) -> Self:
        """Decode every DDL column, including generated columns; never coerce."""
        values = cls._values(record)
        missing = set(cls.COLUMNS) - values.keys()
        unknown = values.keys() - set(cls.COLUMNS)
        if missing or unknown:
            raise ValueError(
                f"{{cls.__name__}} requires a full row; "
                f"missing={{sorted(missing)}}, unknown={{sorted(map(str, unknown))}}"
            )
        return cls(**values)

    @classmethod
    def insert_bindings(
        cls, record: Mapping[str, object] | Row
    ) -> tuple[tuple[str, ...], tuple[_Value, ...]]:
        """Bind supplied writable fields in DDL order, leaving SQL defaults out."""
        values = cls._values(record)
        unknown = values.keys() - set(cls.COLUMNS)
        if unknown:
            raise ValueError(f"unknown columns: {{sorted(map(str, unknown))}}")
        generated = values.keys() - set(cls.WRITE_COLUMNS)
        if generated:
            raise ValueError(
                f"generated/hidden columns are not writable: {{sorted(generated)}}"
            )
        missing = set(cls.WRITE_COLUMNS) - cls._DEFAULT_COLUMNS - values.keys()
        if missing:
            raise ValueError(f"missing required columns: {{sorted(missing)}}")
        columns = tuple(column for column in cls.WRITE_COLUMNS if column in values)
        for column in columns:
            cls._validate_value(column, values[column])
        return columns, tuple(values[column] for column in columns)

    def key_values(self) -> tuple[_Value, ...]:
        """Return the exact ordered DDL primary key."""
        return tuple(getattr(self, column) for column in self.KEY_COLUMNS)
'''


def _tuple_assignment(name: str, values: list[str], indent: str = "    ") -> list[str]:
    if not values:
        return [f"{indent}{name} = ()"]
    if len(values) == 1:
        return [f"{indent}{name} = ({json.dumps(values[0])},)"]
    return [
        f"{indent}{name} = (",
        *(f"{indent}    {json.dumps(value)}," for value in values),
        f"{indent})",
    ]


def render_modules(model: dict, catalog: dict) -> dict[str, str]:
    """Render deterministic modules from DDL metadata; never import row modules."""
    modules = {}
    for domain, store in TARGET_FORMATS.items():
        schema = catalog["stores"][store]
        records = sorted(
            (record for record in model["classes"] if record["domain"] == domain),
            key=lambda record: record["table"],
        )
        lines = [
            HEADER.format(
                domain=domain.title(), store=store, digest=schema["ddl_sha256"]
            ).rstrip()
        ]
        for record in records:
            binding = row_type_binding(record)
            table = schema["tables"][record["table"]]
            columns = sorted(table["columns"], key=lambda column: column["cid"])
            lines.extend(
                [
                    "",
                    "",
                    "@dataclass(frozen=True)",
                    f"class {binding['symbol']}(_Row):",
                    f'    """Full `{store}.{record["table"]}` record."""',
                    "",
                ]
            )
            for column in columns:
                try:
                    primitive = SQL_TYPES[column["type"]]
                except KeyError as exc:
                    raise ValueError(
                        f"unsupported row column type: {store}.{record['table']}."
                        f"{column['name']} {column['type']}"
                    ) from exc
                nullable = " | None" if not column["notnull"] else ""
                lines.append(f"    {column['name']}: {primitive}{nullable}")
            lines.append("")
            for name, values in (
                ("COLUMNS", [column["name"] for column in columns]),
                (
                    "WRITE_COLUMNS",
                    [
                        column["name"]
                        for column in columns
                        if not column["is_generated"] and not column["is_hidden"]
                    ],
                ),
                ("KEY_COLUMNS", table["primary_key"]),
            ):
                lines.extend(_tuple_assignment(name, values))
            codecs = [
                f"({SQL_TYPES[column['type']]}, {not column['notnull']})"
                for column in columns
            ]
            if len(codecs) == 1:
                lines.append(f"    _CODECS = ({codecs[0]},)")
            else:
                lines.append("    _CODECS = (")
                lines.extend(f"        {codec}," for codec in codecs)
                lines.append("    )")
            defaults = [
                column["name"]
                for column in columns
                if column["default_value"] is not None
                and not column["is_generated"]
                and not column["is_hidden"]
            ]
            if len(defaults) == 1:
                lines.append(
                    f"    _DEFAULT_COLUMNS = frozenset(({json.dumps(defaults[0])},))"
                )
            elif defaults:
                lines.extend(["    _DEFAULT_COLUMNS = frozenset(", "        ("])
                lines.extend(f"            {json.dumps(name)}," for name in defaults)
                lines.extend(["        )", "    )"])
        lines.extend(["", "", "ROW_TYPES: dict[str, type[_Row]] = {"])
        lines.extend(
            f"    {json.dumps(record['table'])}: {row_type_binding(record)['symbol']},"
            for record in records
        )
        lines.extend(["}", ""])
        path = row_type_binding({"domain": domain, "id": "Unused.Unused"})["path"]
        modules[path] = "\n".join(lines)
    return modules


def check_generated(model: dict, catalog: dict, root: Path = ROOT) -> list[str]:
    """Check bytes without changing files or importing generated modules."""
    errors = []
    for source, expected in render_modules(model, catalog).items():
        try:
            actual = (root / source).read_bytes().decode("utf-8")
        except OSError:
            actual = None
        if actual != expected:
            errors.append("stale generated persistence rows: " + source)
    return errors


def write_generated(modules: dict[str, str], root: Path = ROOT) -> None:
    """Preflight the whole batch, then atomically replace each generated file.

    This guards ordinary filesystem aliases, not hostile concurrent filesystem
    changes. Replacement is atomic per file, not a transaction across the batch.
    """
    root_metadata = root.lstat()
    if not stat.S_ISDIR(root_metadata.st_mode):
        raise ValueError("generated row root must be a real directory")
    destinations = []
    for source, contents in modules.items():
        relative = Path(source)
        if (
            relative.is_absolute()
            or not relative.parts
            or ".." in relative.parts
            or relative.as_posix() != source
        ):
            raise ValueError(
                "generated row path must be normalized and repository-relative"
            )
        path = root / relative
        # lstat also detects dangling symlinks; exists()/is_file() would follow
        # aliases. Inspect every existing parent before creating any directories.
        parent = root
        for component in relative.parts[:-1]:
            parent /= component
            try:
                metadata = parent.lstat()
            except FileNotFoundError:
                continue
            if not stat.S_ISDIR(metadata.st_mode):
                raise ValueError(
                    "generated row parent must be a real directory: " + str(parent)
                )
        mode = 0o644
        try:
            metadata = path.lstat()
        except FileNotFoundError:
            pass
        else:
            if not stat.S_ISREG(metadata.st_mode) or metadata.st_nlink != 1:
                raise ValueError(
                    "generated row destination must be a regular single-link file: "
                    + source
                )
            mode = stat.S_IMODE(metadata.st_mode)
        destinations.append((path, contents.encode("utf-8"), mode))

    staged = []
    try:
        for path, contents, mode in destinations:
            path.parent.mkdir(parents=True, exist_ok=True)
            descriptor, temporary = tempfile.mkstemp(
                prefix="." + path.name + ".", suffix=".tmp", dir=path.parent
            )
            temporary = Path(temporary)
            staged.append((temporary, path))
            with os.fdopen(descriptor, "wb") as output:
                output.write(contents)
            temporary.chmod(mode)
        for temporary, path in staged:
            temporary.replace(path)
    finally:
        for temporary, _ in staged:
            temporary.unlink(missing_ok=True)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group()
    action.add_argument(
        "--write", action="store_true", help="write generated row modules"
    )
    action.add_argument(
        "--check", action="store_true", help="check generated rows (default)"
    )
    args = parser.parse_args(argv)
    try:
        model, catalog = load_model(), build_catalog()
        # First generation must work before the declared files/classes exist.
        errors = validate_model(model, catalog, inspect_row_types=not args.write)
        if not errors:
            if args.write:
                write_generated(render_modules(model, catalog), ROOT)
            else:
                errors = check_generated(model, catalog, ROOT)
    except (OSError, ValueError, TypeError) as exc:
        print("Persistence row generation failed: " + str(exc), file=sys.stderr)
        return 1
    if errors:
        for error in errors:
            print("Persistence row generation: " + error, file=sys.stderr)
        return 1
    print("Persistence rows " + ("written" if args.write else "OK") + ": seven domains")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
